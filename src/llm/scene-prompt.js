/**
 * tavern-dice / src/llm/scene-prompt.js
 * ---------------------------------------------------------------------------
 * 「让正文模型现写一份战斗场景」的提示词与模板。
 *
 * ## 为什么要有这个
 *
 * 开战不再被动读已有剧情（剧情里恰好没在打就读不出人），而是**主动驱动**：
 * 点开战 → 自动把指令写进输入框发给正文模型 → 它当场写出一份战斗场景 → 解析 → 开打。
 *
 * ## 模板为什么做成「表格填空」
 *
 * 早期版本用「- 技能：」这种自由格式，结果是模型大量写推辞：
 * 「剧情只提到她是中级治愈术士」「具体术式未展开——未知」，
 * 这些被解析成技能名，战斗按钮上就显示出一堆垃圾，而且没有可掷骰的数值。
 *
 * **加「职业模板」去猜职业是治标** —— 一千张卡就有一千种职业，猜不完。
 * 正确的做法是让**模板本身规范到没法含糊**：
 *   - 技能写成 `名字｜范围｜效果类型｜威力｜消耗｜持续回合｜回合豁免DC｜效果说明`；
 *   - 每招明确分类，允许用 + 连接多种受支持效果，不从职业或名字猜范围与机制；
 *   - 威力与消耗都要求**纯数字**，并给量级参照；
 *   - 明令禁止「未知」「未提及」这类占位。
 * 表格天然填不出推辞，解析器也就只需要老老实实读它。
 */

